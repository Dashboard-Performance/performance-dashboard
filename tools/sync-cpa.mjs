// Copies the RE-CPA core (js/cpa-core.js + css/cpa.css) into the merchant portal Worker, which serves them as its own static files.
// Run after any change to those two files:   node tools/sync-cpa.mjs     (test: merchant-portal/test/notify.mjs checks they match)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url"; // Windows-safe (C:\ paths, spaces)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const js = fs.readFileSync(path.join(root, "js/cpa-core.js"), "utf8"), css = fs.readFileSync(path.join(root, "css/cpa.css"), "utf8");
fs.writeFileSync(path.join(root, "merchant-portal/src/cpa-core.js"), "// GENERATED by tools/sync-cpa.mjs from js/cpa-core.js + css/cpa.css — do not edit here.\nexport const CPA_JS = " + JSON.stringify(js) + ";\nexport const CPA_CSS = " + JSON.stringify(css) + ";\n");
console.log("merchant-portal/src/cpa-core.js updated");
